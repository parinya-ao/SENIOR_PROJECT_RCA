#pragma once

#include "arq_diagnostics.h"

namespace arq::app {

/// Snapshot of the fields consumed by the incremental STATUS formatter.
struct BenchStatus {
  int16_t startup;           ///< Radio initialization status.
  uint8_t reset_flags;       ///< Captured MCU reset flags.
  bool ready;                ///< Whether the radio can accept work.
  uint32_t deliveries;       ///< Newly delivered DATA frames.
  uint32_t duplicates;       ///< Repeated DATA frames.
  uint32_t generated;        ///< Responses generated by the receiver.
  uint32_t suppressed;       ///< Responses dropped by fault injection.
  uint32_t attempted;        ///< Transmissions attempted.
  uint32_t completed;        ///< Responses successfully transmitted.
  uint32_t crc_errors;       ///< Packets rejected by the PHY CRC.
  uint32_t rx_done;          ///< Receive completions observed.
  uint32_t decode_errors;    ///< Frames rejected by the codec.
  uint32_t control_rejects;  ///< Control frames rejected by the sender.
  int16_t result;            ///< Sender transaction result code.
  uint8_t state;             ///< Sender transaction state.
  uint32_t rtt[4];  ///< Last, minimum, maximum, and count of RTT samples.
};

/// Captures radio configuration before a subsequent mode transition.
void RecordRadioRegisters(const diagnostics::EventContext& context,
                          const char* name);
/// Captures receive IRQ flags and FIFO counters before a receive restart.
void RecordReceiveDiagnostics(const diagnostics::EventContext& context,
                              const char* name, uint16_t flags);
/// Emits one pending STATUS line when the logger has drained.
void FlushBenchStatus(uint8_t& next, const diagnostics::EventContext& context,
                      const BenchStatus& status);

}  // namespace arq::app
