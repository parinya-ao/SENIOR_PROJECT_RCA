def utc():
    return datetime.now(UTC).isoformat()


def preservation_diff(root, expected_hashes, allowed_changes=()):
    root = Path(root)
    allowed = set(allowed_changes)
    unexpected = []
    authorized = {}
    for name, expected in expected_hashes.items():
        path = root / name
        actual = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None
        if actual == expected:
            continue
        entry = {"expected_sha256": expected, "actual_sha256": actual}
        if name in allowed:
            authorized[name] = entry
        else:
            unexpected.append(name)
    return {"unexpected": unexpected, "authorized_changes": authorized}


def startup_profile(path):
    tree = ast.parse(Path(path).read_text())
    updi = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "UPDI")
    init = next(n for n in updi.body if isinstance(n, ast.FunctionDef) and n.name == "__init__")
    breaks = sum(
        isinstance(n, ast.Call)
        and isinstance(n.func, ast.Attribute)
        and n.func.attr == "send_break"
        for n in ast.walk(init)
    )
    serial_updi = next(
        n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "SerialUPDI"
    )
    serial_init = next(
        n for n in serial_updi.body if isinstance(n, ast.FunctionDef) and n.name == "__init__"
    )
    reset_default = next(
        a
        for a in serial_init.args.defaults
        if isinstance(a, ast.Constant) and isinstance(a.value, bool)
    )
    return {
        "break_calls": breaks,
        "startup_reset": reset_default.value,
        "normal_monitor_startup_authorized": breaks == 2 and reset_default.value is False,
    }


class Gate1Audit:
    def __init__(self, directory):
        self.directory = Path(directory)
        self.lock = threading.RLock()
        self.current_transaction = None
        self.expected_length = None
        self.expected_value = None
        self.operation = "INITIALIZATION"
        self.trace = self.directory / "transport-trace.jsonl"
        self.acquisition = self.directory / "acquisition-events.jsonl"
        self.stdout = self.directory / "monitor.stdout.log"
        self.stderr = self.directory / "monitor.stderr.log"
        self.transactions = self.directory / "status-transactions.jsonl"
        self.break_count = 0
        self.synch_count = 0
        self.resume_count = 0
        self.reset_count = 0
        self.last_complete_request_hex = None
        self.updi_operation = "UNKNOWN"
        self.updi_instruction_hex = None
        self.device_path = None
        self.adapter_identity = "UNKNOWN"
        self.status_command_hex = None
        self.current_status_output = bytearray()
        self.status_command_bytes_sent = []
        self.mailbox_snapshots = []
        self.rows = []
        self.first_failure = None
        self.stdout_stream = None

    def _append(self, path, record, durable=False):
        with self.lock, path.open("a", encoding="utf-8") as stream:
            stream.write(json.dumps(record, sort_keys=True) + "\n")
            stream.flush()
            if durable:
                os.fsync(stream.fileno())

    def event(self, name, **values):
        self._append(
            self.acquisition,
            {
                "timestamp_utc": utc(),
                "timestamp_monotonic_ns": time.monotonic_ns(),
                "host_process_id": os.getpid(),
                "event": name,
                **values,
            },
            True,
        )

    def transport(self, **record):
        self._append(
            self.trace,
            {
                "timestamp_utc": utc(),
                "timestamp_monotonic_ns": time.monotonic_ns(),
                "transaction_index": self.current_transaction,
                "operation_name": self.operation,
                "updi_operation": self.updi_operation,
                "updi_instruction_hex": self.updi_instruction_hex,
                "device_path": self.device_path,
                "adapter_identity": self.adapter_identity,
                "host_process_id": os.getpid(),
                "expected_response_length": self.expected_length,
                "expected_response_value_hex": None
                if self.expected_value is None
                else self.expected_value.hex(),
                **record,
            },
        )

    def fail(self, error, operation, failure_layer=None):
        if self.first_failure is not None:
            return
        if failure_layer == "STATUS_RESPONSE":
            payload = bytes(self.current_status_output)
            self.first_failure = {
                "timestamp_utc": utc(),
                "timestamp_monotonic_ns": time.monotonic_ns(),
                "transaction_index": self.current_transaction,
                "operation_name": operation,
                "failure_boundary": "STATUS_MONITOR_OUTPUT",
                "command": "STATUS",
                "host_tx_hex": self.status_command_hex,
                "host_tx_length": len(bytes.fromhex(self.status_command_hex or "")),
                "expected_response_length": None,
                "expected_response_value": "complete event block ending in STATUS_END v=0",
                "actual_monitor_stdout_hex": payload.hex(),
                "actual_monitor_stdout_length": len(payload),
                "last_updi_request_hex": self.last_complete_request_hex,
                "exception_type": type(error).__name__,
                "exception_message": str(error),
                "previous_successful_transaction": self.rows[-1] if self.rows else None,
                "monitor_exit_code": None,
                "monitor_failure": None,
            }
            self._append(self.directory / "first-failure.json", self.first_failure, True)
            return
        self.first_failure = {
            "timestamp_utc": utc(),
            "timestamp_monotonic_ns": time.monotonic_ns(),
            "transaction_index": self.current_transaction,
            "operation_name": operation,
            "exception_type": type(error).__name__,
            "exception_message": str(error),
            "last_complete_request_hex": self.last_complete_request_hex,
            "expected_response_length": self.expected_length,
            "expected_response_value_hex": None
            if self.expected_value is None
            else self.expected_value.hex(),
            "actual_rx_hex": self.trace_last_rx(),
            "actual_rx_length": self.trace_last_rx_length(),
            "previous_successful_transaction": self.rows[-1] if self.rows else None,
        }
        self._append(self.directory / "first-failure.json", self.first_failure, True)

    def trace_last_rx(self):
        try:
            lines = self.trace.read_text().splitlines()
            for line in reversed(lines):
                item = json.loads(line)
                if (
                    item.get("direction") == "read"
                    and item.get("transaction_index") == self.current_transaction
                ):
                    return item.get("actual_rx_hex", "UNKNOWN")
        except (OSError, json.JSONDecodeError):
            pass
        return "UNKNOWN"

    def trace_last_rx_length(self):
        try:
            lines = self.trace.read_text().splitlines()
            for line in reversed(lines):
                item = json.loads(line)
                if (
                    item.get("direction") == "read"
                    and item.get("transaction_index") == self.current_transaction
                ):
                    return item.get("actual_rx_length", "UNKNOWN")
        except (OSError, json.JSONDecodeError):
            pass
        return "UNKNOWN"

    def write_transaction(self, row):
        self.rows.append(row)
        self._append(self.transactions, row, True)


class TracePort:
    """Transparent serial proxy: delegates unchanged and records returned bytes."""

    def __init__(self, port, audit):
        object.__setattr__(self, "_port", port)
        object.__setattr__(self, "_audit", audit)

    def __getattr__(self, name):
        return getattr(self._port, name)

    def __setattr__(self, name, value):
        setattr(self._port, name, value)

    def write(self, data):
        start = time.monotonic_ns()
        settings = {
            "baudrate": self.baudrate,
            "parity": self.parity,
            "stopbits": self.stopbits,
            "read_timeout_s": self.timeout,
            "write_timeout_s": self.write_timeout,
        }
        try:
            result = self._port.write(data)
        except Exception as exc:
            self._audit.transport(
                direction="write",
                host_tx_hex=bytes(data).hex(),
                host_tx_length=len(data),
                serial_write_start_ns=start,
                serial_write_end_ns=time.monotonic_ns(),
                serial_settings=settings,
                exception_type=type(exc).__name__,
                exception_message=str(exc),
            )
            raise
        self._audit.transport(
            direction="write",
            host_tx_hex=bytes(data).hex(),
            host_tx_length=len(data),
            bytes_written=result,
            serial_write_start_ns=start,
            serial_write_end_ns=time.monotonic_ns(),
            serial_settings=settings,
        )
        return result

    def read(self, length):
        start = time.monotonic_ns()
        settings = {
            "baudrate": self.baudrate,
            "parity": self.parity,
            "stopbits": self.stopbits,
            "read_timeout_s": self.timeout,
            "write_timeout_s": self.write_timeout,
        }
        try:
            data = self._port.read(length)
        except Exception as exc:
            self._audit.transport(
                direction="read",
                requested_response_length=length,
                actual_rx_hex="UNKNOWN",
                actual_rx_length="UNKNOWN",
                serial_read_start_ns=start,
                serial_read_end_ns=time.monotonic_ns(),
                serial_settings=settings,
                exception_type=type(exc).__name__,
                exception_message=str(exc),
            )
            raise
        self._audit.transport(
            direction="read",
            requested_response_length=length,
            actual_rx_hex=bytes(data).hex(),
            actual_rx_length=len(data),
            serial_read_start_ns=start,
            serial_read_end_ns=time.monotonic_ns(),
            serial_settings=settings,
        )
        return data


class MonitorConsole:
    def __init__(self):
        self.input = queue.Queue()
        self.output = queue.Queue()

    def get(self):
        return self.input.get()

    def put(self, byte):
        self.output.put((byte, time.monotonic_ns()))

    def send(self, data):
        for byte in data:
            self.input.put(byte)


def instrument(module, audit, serial_module):
    real_serial = serial_module.Serial

    def open_exclusive(*args, **kwargs):
        kwargs["exclusive"] = True
        raw = real_serial(*args, **kwargs)
        audit.event(
            "SERIAL_PORT_OPEN",
            device_path=str(args[0]),
            baudrate=args[1],
            parity=kwargs.get("parity"),
            stopbits=kwargs.get("stopbits"),
            exclusive=True,
        )
        return TracePort(raw, audit)

    serial_module.Serial = open_exclusive
    original_break = module.SerialPort.send_break

    def send_break(self):
        audit.break_count += 1
        audit.event(
            "UPDI_BREAK_START", break_index=audit.break_count, baudrate_before=self.dev.baudrate
        )
        try:
            return original_break(self)
        except Exception as exc:
            audit.fail(exc, "UPDI_BREAK")
            raise
        finally:
            audit.event(
                "UPDI_BREAK_END", break_index=audit.break_count, baudrate_after=self.dev.baudrate
            )

    module.SerialPort.send_break = send_break

    original_instr = module.UPDI.instr

    def instr(self, data):
        audit.synch_count += 1
        caller = inspect.currentframe().f_back.f_code.co_name
        old_operation, old_instruction = audit.updi_operation, audit.updi_instruction_hex
        audit.updi_operation = "UPDI." + caller
        audit.updi_instruction_hex = bytes(data).hex()
        audit.operation = "UPDI_SYNCH_INSTRUCTION"
        try:
            return original_instr(self, data)
        except Exception as exc:
            audit.fail(exc, audit.operation)
            raise
        finally:
            audit.updi_operation = old_operation
            audit.updi_instruction_hex = old_instruction

    module.UPDI.instr = instr

    for cls, method in [
        (module.SerialPort, "send"),
        (module.SerialPort, "recv"),
        (module.UPDI, "key"),
        (module.UPDI, "reset"),
        (module.SerialUPDI, "send1"),
        (module.SerialUPDI, "recv1"),
    ]:
        original = getattr(cls, method)

        def wrapper(self, *args, __original=original, __name=method, **kwargs):
            old = audit.operation
            audit.operation = f"{type(self).__name__}.{__name}"
            if __name == "send" and args:
                audit.expected_length = len(args[0])
                audit.expected_value = bytes(args[0])
            elif __name == "recv" and args:
                audit.expected_length = args[0]
                audit.expected_value = args[1] if len(args) > 1 else kwargs.get("expected")
            try:
                result = __original(self, *args, **kwargs)
                if __name == "send1" and result and audit.current_transaction is not None and args:
                    value = int(args[0]) & 0xFF
                    audit.status_command_bytes_sent.append(value)
                    audit.event(
                        "STATUS_MAILBOX_BYTE_ACCEPTED",
                        transaction_index=audit.current_transaction,
                        byte_hex=f"{value:02x}",
                    )
                if __name == "send" and args:
                    audit.last_complete_request_hex = bytes(args[0]).hex()
                if __name == "reset":
                    audit.reset_count += 1
                    audit.event(
                        "CONTROLLED_CPU_RESET", operation="UPDI.reset", count=audit.reset_count
                    )
                return result
            except Exception as exc:
                audit.fail(exc, audit.operation)
                raise
            finally:
                audit.operation = old
                if __name in ("recv", "send"):
                    audit.expected_length = None
                    audit.expected_value = None

        setattr(cls, method, wrapper)

    original_ldcs = module.UPDI.ldcs

    def ldcs(self, address):
        value = original_ldcs(self, address)
        if address == module.ASI_OCD_STATUS and value & module.OCD_STOPPED:
            audit.event("OCD_STOP_OBSERVED", status=value)
        return value

    module.UPDI.ldcs = ldcs

    original_stcs = module.UPDI.stcs

    def stcs(self, address, value):
        if address == module.ASI_OCD_CTRLA and value == module.OCD_RUN:
            audit.resume_count += 1
            audit.event("OCD_CPU_RESUME", address=address, value=value, count=audit.resume_count)
        return original_stcs(self, address, value)

    module.UPDI.stcs = stcs
    return real_serial


def _parse_block(lines, expected):
    events = [parse_event(line) for line in lines]
    if not events or any(event is None for event in events):
        raise ValueError("status event parse failure")
    role = expected["role"]
    for event in events:
        event["role"] = role
    names = [event["e"] for event in events]
    if not {
        "BOOT",
        "IDENTITY",
        "STATUS",
        "RESULT",
        "RTT_LAST",
        "RTT_MIN",
        "RTT_MAX",
        "RTT_COUNT",
        "RX_DONE_COUNT",
        "DECODE_ERRORS",
        "CONTROL_REJECTS",
        "REG",
        "STATUS_END",
    } <= set(names):
        raise ValueError("incomplete STATUS block")
    if not status_complete(events, role, 0):
        raise ValueError("STATUS_END missing, reordered, or overflowed")
    if any(int(event["s"], 16) != 0 for event in events):
        raise ValueError("STATUS session is not idle")
    status = next(event for event in events if event["e"] == "STATUS")
    identity = next(event for event in events if event["e"] == "IDENTITY")
    if status.get("ready") != "1" or status.get("overflow") != "0":
        raise ValueError("STATUS reports not-ready radio or logger overflow")
    if (
        identity.get("build") != expected["build_id"]
        or identity.get("config") != expected["config_hash"]
    ):
        raise ValueError("firmware build/config identity mismatch")
    return events


def firmware_identity_from_events(events):
    identity = next((event for event in events if event.get("e") == "IDENTITY"), None)
    if identity is None:
        return None
    return {
        "build_id": identity.get("build"),
        "config_hash": identity.get("config"),
        "role": identity.get("role"),
    }


def wait_for_reader_idle(reader_busy, timeout_s):
    deadline = time.monotonic() + max(0, timeout_s)
    while reader_busy.locked() and time.monotonic() < deadline:
        time.sleep(0.005)
    return not reader_busy.locked()


def _readline(console, audit, terminal, deadline, output_file):
    line = bytearray()
    while time.monotonic() < deadline:
        if terminal.failure is not None:
            raise terminal.failure
        try:
            byte, host_ns = console.output.get(
                timeout=min(0.05, max(0.001, deadline - time.monotonic()))
            )
        except queue.Empty:
            continue
        raw = bytes([byte])
        if audit.current_transaction is not None:
            audit.current_status_output.extend(raw)
        output_file.write(raw)
        if byte == 0x0A:
            output_file.flush()
        line.extend(raw)
        if byte == 0x0A:
            return line.decode("ascii", errors="replace").rstrip("\r\n"), bytes(line)
        if len(line) > 8192:
            raise ValueError("monitor line exceeds 8192 bytes")
    raise TimeoutError("STATUS acquisition or transaction deadline")


def _read_block(console, audit, terminal, expected, deadline, output_file, startup=False):
    lines, events, raw_block = [], [], bytearray()
    seen_boot = False
    ignored_prefix_count = 0
    ignored_prefix_sample = []
    while time.monotonic() < deadline:
        line, raw_line = _readline(console, audit, terminal, deadline, output_file)
        event = parse_event(line)
        if startup and not seen_boot and (event is None or event["e"] != "BOOT"):
            ignored_prefix_count += 1
            if len(ignored_prefix_sample) < 8:
                ignored_prefix_sample.append(raw_line.hex())
            continue
        if startup and not seen_boot:
            seen_boot = True
            if ignored_prefix_count:
                audit.event(
                    "STARTUP_OUTPUT_PREFIX_IGNORED",
                    line_count=ignored_prefix_count,
                    sample_hex=ignored_prefix_sample,
                )
        lines.append(line)
        raw_block.extend(raw_line)
        if event:
            events.append(event)
            if event["e"] == "STATUS_END":
                break
        if len(lines) > 64:
            raise ValueError("STATUS output exceeded bounded event count")
    if not lines or not events or events[-1]["e"] != "STATUS_END":
        raise TimeoutError("incomplete STATUS_END before deadline")
    if startup and not seen_boot:
        raise ValueError("startup block did not contain BOOT")
    parsed = _parse_block(lines, expected)
    return lines, parsed, bytes(raw_block)


def read_data_space_byte(updi, address):
    """Read one byte using the AVR128DA 16-bit-address, byte-data LDS form."""
    if type(address) is not int or not 0 <= address <= 0xFFFF:
        raise ValueError("AVR128DA data-space address must fit in 16 bits")
    # DS40002183C Figure 35-6: SizeA=01 (16-bit address), SizeB=00 (byte) => LDS 0x04.
    updi.instr([0x04, address & 0xFF, address >> 8])
    return updi.recv(1)[0]


def store_data_space_byte(updi, address, value):
    if type(address) is not int or not 0 <= address <= 0xFFFF:
        raise ValueError("AVR128DA data-space address must fit in 16 bits")
    if type(value) is not int or not 0 <= value <= 0xFF:
        raise ValueError("data-space byte must fit in 8 bits")
    updi.instr([0x44, address & 0xFF, address >> 8])
    updi.recv(1, bytes([0x40]))
    updi.send([value])
    updi.recv(1, bytes([0x40]))


def sts8_with_wide_gpr_address(updi, address, value, original_sts8):
    if 0x1C <= address <= 0x1F:
        return store_data_space_byte(updi, address, value)
    return original_sts8(updi, address, value)


def roundtrip_gpr_16(updi, address):
    before = read_data_space_byte(updi, address)
    test_value = before ^ 0xFF
    try:
        store_data_space_byte(updi, address, test_value)
        readback = read_data_space_byte(updi, address)
        readback8 = updi.lds8(address)
    finally:
        store_data_space_byte(updi, address, before)
    return {
        "address": address,
        "before": before,
        "test_value": test_value,
        "readback": readback,
        "readback8": readback8,
        "restored": read_data_space_byte(updi, address),
        "restored8": updi.lds8(address),
    }


def gpr_roundtrip_succeeded(result, alternate_readback, alternate_restored):
    return (
        (result["readback"] == result["test_value"] or alternate_readback == result["test_value"])
        and result["restored"] == result["before"]
        and alternate_restored == result["before"]
    )


def mailbox_snapshot(updi):
    """Capture volatile mailbox, startup reset copy and OCD flags using reads only."""
    return {
        "uart_flags": updi.lds8(0x1E),  # GPIOR2
        "uart_rx": updi.lds8(0x1F),  # GPIOR3
        "app_reset_flags": updi.lds8(0x1C),  # GPIOR0 captured by setup()
        "rstfr": updi.lds8(0x40),  # RSTCTRL.RSTFR
        "ocd_status": updi.ldcs(0x05),  # ASI_OCD_STATUS
        "ocd_message_status": read_data_space_byte(updi, 0x0F19),  # SYSCFG_OCDMS
    }


def reenable_uart_output(updi, flags_address, enable_flag):
    before = updi.lds8(flags_address)
    write = before | enable_flag
    if write != before:
        updi.sts8(flags_address, write)
    return {
        "before": before,
        "after": updi.lds8(flags_address),
        "write": write if write != before else None,
    }


def roundtrip_gpr(updi, address):
    before = updi.lds8(address)
    test_value = before ^ 0xFF
    try:
        updi.sts8(address, test_value)
        readback = updi.lds8(address)
        readback16 = read_data_space_byte(updi, address)
    finally:
        updi.sts8(address, before)
    return {
        "address": address,
        "before": before,
        "test_value": test_value,
        "readback": readback,
        "readback16": readback16,
        "restored": updi.lds8(address),
        "restored16": read_data_space_byte(updi, address),
    }


def halted_gpr_roundtrip(
    updi,
    address,
    ctrl_address,
    status_address,
    stop_command,
    run_command,
    stopped_mask,
    timeout_s=2,
    probe=roundtrip_gpr,
):
    before_status = updi.ldcs(status_address)
    if before_status & stopped_mask:
        raise RuntimeError("CPU was already stopped; refusing to change its execution state")
    updi.stcs(ctrl_address, stop_command)
    failure = None
    try:
        deadline = time.monotonic() + timeout_s
        while True:
            halt_status = updi.ldcs(status_address)
            if halt_status & stopped_mask:
                break
            if time.monotonic() >= deadline:
                raise TimeoutError("OCD did not confirm CPU stop")
            time.sleep(0.001)
        scratch = probe(updi, address)
    except Exception as exc:
        failure = exc
    try:
        updi.stcs(ctrl_address, run_command)
        deadline = time.monotonic() + timeout_s
        while True:
            resumed_status = updi.ldcs(status_address)
            if not resumed_status & stopped_mask:
                break
            if time.monotonic() >= deadline:
                raise TimeoutError("OCD did not confirm CPU resume")
            time.sleep(0.001)
    except Exception as resume_error:
        if failure is not None:
            raise RuntimeError(f"{failure}; CPU resume failed: {resume_error}") from failure
        raise
    if failure is not None:
        raise failure
    return {
        "before_status": before_status,
        "halt_status": halt_status,
        "scratch": scratch,
        "resumed_status": resumed_status,
    }


def read_updi_pesig(updi):
    return updi.ldcs(0x01)  # STATUSB.PESIG is read-to-clear; call once after raw trace capture.


def target_profile(target, hardware, verified, config_hash):
    role = {"receiver": "receiver", "gateway": "sender"}.get(target)
    if role is None or target not in hardware:
        raise ValueError("target must be a configured receiver or gateway")
    device = hardware[target]
    port_path = device["port_path"]
    return {
        "port_path": port_path,
        "device_serial_hex": device["device_serial_hex"],
        "udev_path": Path(port_path).name.rsplit("-port", 1)[0],
        "firmware_role": role,
        "expected_identity": {
            "build_id": verified[role]["build_id"],
            "config_hash": config_hash,
            "role": role,
        },
    }


def controlled_cpu_reset(updi, ocd_key):
    updi.reset()
    updi.key(ocd_key)


def resume_cpu_if_stopped(
    updi, ctrl_address, status_address, run_command, stopped_mask, timeout_s=2
):
    before = updi.ldcs(status_address)
    if not before & stopped_mask:
        return {"before_status": before, "run_requested": False, "after_status": before}
    updi.stcs(ctrl_address, run_command)
    deadline = time.monotonic() + timeout_s
    while True:
        after = updi.ldcs(status_address)
        if not after & stopped_mask:
            return {"before_status": before, "run_requested": True, "after_status": after}
        if time.monotonic() >= deadline:
            raise TimeoutError("OCD did not confirm CPU resume after controlled reset")
        time.sleep(0.001)


def part_from_signature(signature):
    return "AVR128DA28" if signature == bytes.fromhex("1e970a") else None


